import { describe, expect, it } from "vitest";
import { prModel } from "../testing/factories.ts";
import { type AiSign, aiReader, NO_AI_CONFIG, toolsOf } from "./ai.ts";
import type { PrModel } from "./model.ts";

const read = aiReader();
const files = (...paths: string[]) => paths.map((path) => ({ path, additions: 1, deletions: 0 }));
const commit = (message: string, sha = "abc1234def") => ({
  sha,
  authoredAt: "2026-03-01T10:00:00Z",
  committedAt: "2026-03-01T10:00:00Z",
  message,
});
const markers = (pr: Partial<PrModel>, reader = read) =>
  reader(prModel(pr)).map((sign) => sign.marker);

describe("AI markers", () => {
  it("finds each kind of marker, with where it was seen [rule 20]", () => {
    const signs = read(
      prModel({
        files: files(
          "src/app.ts",
          "thoughts/shared/plans/2026-03-01-parser.md",
          ".claude/commands/review.md",
          "CLAUDE.md",
          "AGENTS.md",
        ),
        body: "Fixes the parser.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
        author: { login: "copilot-swe-agent[bot]", bot: true },
        headBranch: "claude/fix-parser-x1y2",
      }),
    );
    expect(signs).toEqual<AiSign[]>([
      { marker: "thoughts", tool: null, where: "thoughts/shared/plans/2026-03-01-parser.md" },
      { marker: "claudeDir", tool: "Claude", where: ".claude/commands/review.md" },
      { marker: "claudeMd", tool: "Claude", where: "CLAUDE.md" },
      { marker: "agentFiles", tool: "Other", where: "AGENTS.md" },
      {
        marker: "signature",
        tool: "Claude",
        where: "description: 🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      },
      { marker: "agentAuthor", tool: "Copilot", where: "copilot-swe-agent[bot]" },
      { marker: "agentBranch", tool: "Claude", where: "claude/fix-parser-x1y2" },
    ]);
    expect(toolsOf(signs)).toEqual(["Claude", "Copilot", "Other"]);
  });

  it("reads co-author trailers and agents' links in commits, naming the tool [rule 20]", () => {
    const signature = (message: string) =>
      read(prModel({ commits: [commit(message)] })).find((s) => s.marker === "signature");
    expect(signature("Fix\n\nCo-Authored-By: Claude <noreply@anthropic.com>")).toEqual({
      marker: "signature",
      tool: "Claude",
      where: "commit abc1234: Co-Authored-By: Claude <noreply@anthropic.com>",
    });
    expect(
      signature("Fix\n\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>")
        ?.tool,
    ).toBe("Copilot");
    expect(signature("Fix\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>")?.tool).toBe(
      "Cursor",
    );
    expect(signature("aider: fix the parser")?.tool).toBe("Aider");
    expect(signature("Task: https://chatgpt.com/codex/tasks/task_e_123")?.tool).toBe("Codex");
    expect(signature("Generated by GitHub Copilot")?.tool).toBe("Copilot");
  });

  it("isn't fooled by work about a tool, or names that only look like one [rule 20]", () => {
    expect(
      markers({
        title: "Add Claude and Copilot support to the chat panel",
        body: "Generated with care. See docs/thoughts.md.",
        commits: [commit("Co-authored-by: Jane Doe <jane@example.com>")],
        files: files("src/thoughts.ts", "src/components/Cursor.tsx", "docs/agents/setup.md"),
        headBranch: "feature/claude-integration",
        author: { login: "claudette", bot: false },
      }),
    ).toEqual([]);
  });

  it("adds the org's own markers and ignores the built-in ones it doesn't trust", () => {
    const reader = aiReader({
      ...NO_AI_CONFIG,
      files: ["notes/ai/**"],
      text: ["\\[ai-assisted\\]"],
      branches: ["agent/*"],
      authors: ["acme-agent"],
      ignore: ["thoughts"],
    });
    expect(markers({ files: files("thoughts/plan.md") }, reader)).toEqual([]);
    expect(markers({ files: files("notes/ai/x.md") }, reader)).toEqual(["custom"]);
    expect(markers({ title: "Fix it [AI-assisted]" }, reader)).toEqual(["custom"]);
    expect(markers({ headBranch: "agent/fix" }, reader)).toEqual(["custom"]);
    expect(markers({ author: { login: "Acme-Agent", bot: false } }, reader)).toEqual(["custom"]);
  });

  it("finds none on a PR without traces", () => {
    expect(read(prModel())).toEqual([]);
  });
});
